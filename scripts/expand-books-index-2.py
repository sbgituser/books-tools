def main():
    with open(INDEX_PATH, encoding="utf-8") as f:
        existing = json.load(f)

    existing_ids = set()
    existing_titles = set()
    for e in existing:
        existing_ids.add(e.get("id",""))
        existing_ids.add(e.get("isbn13",""))
        existing_titles.add(e.get("title","").lower().strip())

    added = []
    skipped = 0
    for book in NEW_BOOKS:
        isbn = book.get("isbn13","")
        title = book.get("title","").lower().strip()
        if isbn in existing_ids or title in existing_titles:
            skipped += 1
            continue
        added.append(book)
        existing_ids.add(isbn)
        existing_titles.add(title)

    all_entries = existing + added
    with open(INDEX_PATH, "w", encoding="utf-8") as f:
        json.dump(all_entries, f, ensure_ascii=False, indent=2)

    # Update source too
    with open(SOURCE_PATH, encoding="utf-8") as f:
        source = json.load(f)
    source_isbns = set(e.get("isbn13","") for e in source)
    for book in added:
        isbn = book.get("isbn13","")
        if isbn and isbn not in source_isbns:
            source.append({"isbn13": isbn, "_category": ",".join(book.get("keywords",[]))})
            source_isbns.add(isbn)
    with open(SOURCE_PATH, "w", encoding="utf-8") as f:
        json.dump(source, f, ensure_ascii=False, indent=2)

    print(f"Existing: {len(existing)}, Candidates: {len(NEW_BOOKS)}, Skipped: {skipped}, Added: {len(added)}")
    print(f"books.index.json: {len(existing)} → {len(all_entries)}")
    print(f"books.source.json: → {len(source)}")

if __name__ == "__main__":
    main()
