    kw = list(cats)
    if keywords_extra:
        kw.extend(keywords_extra)
    if subjects is None:
        subjects = []
    search_parts = [title] + authors + ([publisher] if publisher else []) + cats + kw
    return {
        "id": isbn13,
        "title": title,
        "authors": authors,
        "categories": cats,
        "keywords": kw,
        "searchableText": " ".join(search_parts),
        "updatedAt": NOW,
        "publisher": publisher,
        "publishedDate": published_date,
        "isbn13": isbn13,
        "language": "ja",
        "pageCount": page_count,
        "subjects": subjects if subjects else [],
    }


