def main():
    # Load existing index
    with open(INDEX_PATH, encoding="utf-8") as f:
        existing = json.load(f)

    existing_ids = set()
    existing_titles_lower = set()
    for entry in existing:
        existing_ids.add(entry.get("id", ""))
        existing_ids.add(entry.get("isbn13", ""))
        existing_titles_lower.add(entry.get("title", "").lower().strip())

    # Filter out duplicates
    added = []
    skipped = []
    for book in NEW_BOOKS:
        isbn = book.get("isbn13", "")
        title = book.get("title", "").lower().strip()
        bid = book.get("id", "")

        if isbn in existing_ids or bid in existing_ids:
            skipped.append(f"[ISBN dup] {book['title']}")
            continue
        if title in existing_titles_lower:
            skipped.append(f"[Title dup] {book['title']}")
            continue

        added.append(book)
        existing_ids.add(isbn)
        existing_ids.add(bid)
        existing_titles_lower.add(title)

    print(f"Existing entries: {len(existing)}")
    print(f"New candidates: {len(NEW_BOOKS)}")
    print(f"Duplicates skipped: {len(skipped)}")
    for s in skipped[:20]:
        print(f"  {s}")
    if len(skipped) > 20:
        print(f"  ... and {len(skipped)-20} more")
    print(f"New entries to add: {len(added)}")

    # Also add to books.source.json
    with open(SOURCE_PATH, encoding="utf-8") as f:
        source = json.load(f)
    source_isbns = set(e.get("isbn13","") for e in source)

    new_source = []
    for book in added:
        isbn = book.get("isbn13", "")
        if isbn and isbn not in source_isbns:
            new_source.append({"isbn13": isbn, "_category": ",".join(book.get("keywords", []))})
            source_isbns.add(isbn)

    # Write updated files
    all_entries = existing + added
    with open(INDEX_PATH, "w", encoding="utf-8") as f:
        json.dump(all_entries, f, ensure_ascii=False, indent=2)
    print(f"\nbooks.index.json: {len(existing)} → {len(all_entries)} entries")

    all_source = source + new_source
    with open(SOURCE_PATH, "w", encoding="utf-8") as f:
        json.dump(all_source, f, ensure_ascii=False, indent=2)
    print(f"books.source.json: {len(source)} → {len(all_source)} entries")


if __name__ == "__main__":
    main()
